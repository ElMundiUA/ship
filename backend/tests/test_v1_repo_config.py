@pytest.mark.asyncio
async def test_read_config_returns_raw_parsed_and_sha(
    monkeypatch, v1_client, seed_workspace_with_repo
) -> None:
    raw, workspace, _install, repo = seed_workspace_with_repo
    _patch_blob(monkeypatch, content=_SAMPLE_CONFIG, sha="sha-abc")

    response = await v1_client.get(
        f"/v1/workspaces/{workspace.id}/repos/{repo.id}/config",
        headers={"Authorization": f"Bearer {raw}"},
    )
    assert response.status_code == 200, response.text
    body = response.json()
    assert body["exists"] is True
    assert body["sha"] == "sha-abc"
    assert body["raw_yaml"] == _SAMPLE_CONFIG
    assert body["parsed"]["preset"] == "web-app"
    assert "pr_review" in body["parsed"]["lanes"]
    assert body["parse_error"] is None


