def _patch_blob(monkeypatch, *, content: str, sha: str = "deadbeef"):
    """Stub ``GitHubCodeHost.get_blob`` to return a predictable blob."""
    from backend.app.integrations.gateway.code_host import BlobContent

    async def _get_blob(self, ref, *, path, ref_sha=None):
        return BlobContent(
            path=path,
            ref=ref_sha or "main",
            sha=sha,
            size=len(content.encode("utf-8")),
            encoding="utf-8",
            content=content,
        )

    monkeypatch.setattr(
        "backend.app.integrations.github.code_host_adapter."
        "GitHubCodeHost.get_blob",
        _get_blob,
    )


def _patch_blob_missing(monkeypatch):
    async def _get_blob(self, ref, *, path, ref_sha=None):
        raise FileNotFoundError(f"{ref.owner}/{ref.repo}:{path}")

    monkeypatch.setattr(
        "backend.app.integrations.github.code_host_adapter."
        "GitHubCodeHost.get_blob",
        _get_blob,
    )


