@pytest.mark.asyncio
async def test_propose_opens_single_file_pr(
    monkeypatch, v1_client, seed_workspace_with_repo
) -> None:
    from backend.app.integrations.github.workflows import StarterWorkflowPR

    raw, workspace, _install, repo = seed_workspace_with_repo
    _patch_blob(monkeypatch, content=_SAMPLE_CONFIG, sha="sha-abc")

    captured: dict[str, object] = {}

    async def _commit(
        repo, install, *, files, title, branch_label, pr_body_header, settings,
        return_url=None, client=None,
    ):
        captured["files"] = files
        captured["title"] = title
        captured["branch_label"] = branch_label
        return StarterWorkflowPR(
            pr_url="https://github.com/acme/lanes-config/pull/7",
            pr_number=7,
            branch="ship/lanes-config-123",
        )

    monkeypatch.setattr(
        "backend.app.integrations.github.workflows.commit_bundle_pr", _commit
    )

    response = await v1_client.post(
        f"/v1/workspaces/{workspace.id}/repos/{repo.id}/config/propose",
        headers={"Authorization": f"Bearer {raw}"},
        json={
            "base_sha": "sha-abc",
            "change_summary": "Pause the weekly tech-debt lane",
            "lanes": {
                "pr_review": {
                    "event": "pull_request",
                    "pattern": "**",
                    "idempotency_key": "{{pr}}",
                },
                "daily_standup": {"schedule": "0 9 * * 1-5"},
            },
        },
    )
    assert response.status_code == 200, response.text
    body = response.json()
    assert body["pr_number"] == 7

    # PR carries exactly one file (.ship/config.yml) and it contains
    # the emitter's canonical output, not arbitrary user bytes.
    files = captured["files"]
    assert isinstance(files, list) and len(files) == 1
    path, content = files[0]
    assert path == ".ship/config.yml"
    assert "preset: web-app" in content
    assert "pr_review:" in content
    assert "daily_standup:" in content


